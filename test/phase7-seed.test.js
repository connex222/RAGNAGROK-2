'use strict';
/* Determinism for browser acceptance without exposing predictable normal seeds. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { RoomManager } = require('../server/rooms');
const { createGame } = require('../src/engine/garden');
const original = Math.random;
const seed = 215063;
console.log('Phase 7 reproducible acceptance checks');
const create = () => new RoomManager({ rules: 'v2', gameSeed: seed, logger: {log(){},error(){}} });
const first = create(), second = create();
const a = first.create(1000), b = second.create(1000);
assert.equal(a.state.secrets.rng.s, seed);
assert.equal(b.state.secrets.rng.s, seed);
assert.deepEqual(a.state.secrets.rng, b.state.secrets.rng);
assert.equal(createGame({ seed, now: 1000 }).secrets.rng.s, seed);
assert.throws(() => new RoomManager({ rules: 'v2', gameSeed: -1 }), /Invalid deterministic test seed/);
assert.throws(() => new RoomManager({ rules: 'v2', gameSeed: 2 ** 32 }), /Invalid deterministic test seed/);
assert.throws(() => new RoomManager({ rules: 'v2', gameSeed: '123' }), /Invalid deterministic test seed/);
assert.equal(new RoomManager({ rules: 'v2' }).gameSeed, undefined);
const server = fs.readFileSync(path.join(__dirname, '../server/index.js'), 'utf8');
assert.match(server, /gameSeed = undefined/);
assert.doesNotMatch(server, /process\.env\.[A-Z_]*SEED/);
const ui = fs.readFileSync(path.join(__dirname, 'ui2.test.js'), 'utf8');
assert.match(ui, /gameSeed: UI_GAME_SEED/);
assert.match(ui, /No progress for 10 s[\s\S]*diagnostics|const diagnostics = phones\.map/);
assert.strictEqual(Math.random, original, 'testing must not patch global RNG');
console.log('  ✔ explicit browser game seed is stable, validated, and unavailable to clients');
console.log('  ✔ ordinary production games retain random seeds');
const phone = fs.readFileSync(path.join(__dirname, '../public/v2/play.html'), 'utf8');
assert.match(phone, /function prayerDestinations\(from, disaster\)/);
assert.match(phone, /No legal destination remains for this forecast/);
assert.match(phone, /if \(index < 0\) \{ toast\('No legal redirect/);
assert.match(ui, /return tapFirst\(p, '\[data-act=\"closeSheet\"\]'\)/);
console.log('  ✔ impossible Pray choices are filtered and browser bot exits the dead end');
console.log('  ✔ stalled-browser diagnostics and full real-network acceptance remain enabled');
